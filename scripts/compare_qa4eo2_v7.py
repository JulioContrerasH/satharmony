#!/usr/bin/env python
"""Comparison 1: every MSS model against the QA4EO-2 labels.

Ground truth
------------
``label_qa4eo_2_60m.tif``, the output of QA4EO-2 on the native 60 m MSS
(``mss_original.tif``), generated by ``scripts/qa4eo2_labels.py``.  The scene
folder now carries a 30 m ``label_qa4eo_2.tif`` from
``scripts/qa4eo2_labels_30m_from_60m.py`` (the 60 m product upsampled, 3
classes), so the 60 m product is the preserved copy and ``reference_path``
refuses anything that is not a 60 m single-band raster.  It is a
**self-consistency** reference, not an independent truth: it says how far each
model is from what QA4EO-2 does on the same pixels.  The independent reference
is TM QA_PIXEL, which this script does not touch (it is in
``benchmark_proxy_v7.py``).

Mask
----
Only the intersection of valid pixels is scored: all four MSS bands strictly
positive **and** the label different from 255.  No no-data pixel enters any
metric, so the confusion matrices of every model are over the same pixels by
construction.

Models
------
``ocm_mss``       OmniCloudMask on MSS (red, green, NIR2) at 60 m.
``qa4eo2_jan4``   the 4-class January export of QA4EO-2
                  (``train/mlstac_export/unet.ckpt``), thin + thick merged.
                  *Old* QA4EO-2: the model the v7 labels were distilled from.
``g4`` / ``g4b``  satharmony U-Nets trained on the uncalibrated fixture.
``g4_cal`` / ``g4b_cal``  same recipe on the calibrated fixture.

Metrics per model
-----------------
Pooled over every valid pixel: 3 x 3 confusion matrix (rows reference), IoU,
precision, recall, F1 per class, mean IoU, overall accuracy and Cohen's kappa.
Per scene: the same mIoU, plus the boundary F1 of cloud and shadow (tolerance
1 pixel at 60 m) and the false-positive fraction over the pixels the reference
calls clear.  Detection at block level (256 x 256, >= 50 % valid, 5 % class
fraction) gives cloud/shadow presence recall and precision.

Usage
-----
    python scripts/compare_qa4eo2_v7.py --models ocm_mss g4 --limit 3
    python scripts/compare_qa4eo2_v7.py
"""

