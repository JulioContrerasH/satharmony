def reference_path(folder: Path) -> Path:
    """Locate the 60 m QA4EO-2 label of one scene.

    Args:
        folder: ``pairs_optimization/<scene>``.

    Returns:
        Path of the 60 m label.

    Raises:
        FileNotFoundError: If only a non-60 m raster is available, so this
            script can never score a 30 m label against 60 m features.
    """
    preserved = folder / REFERENCE_60M
    if preserved.exists():
        return preserved
    current = folder / REFERENCE_FALLBACK
    with rasterio.open(current) as src:
        if src.count == 1 and abs(float(src.transform.a) - 60.0) < 1e-6:
            return current
    raise FileNotFoundError(f"{current} is not a 60 m label and {preserved} is missing")


# ── models ──────────────────────────────────────────────────────────────
def ocm_mask(array: np.ndarray, device: str) -> np.ndarray:
    """OmniCloudMask on a ``(3, H, W)`` reflectance stack (red, green, NIR)."""
    from omnicloudmask import predict_from_array

    size = min(array.shape[-2:])
    patch = min(1000, max(64, 8 * (size // 8)))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return predict_from_array(
            np.ascontiguousarray(array, dtype=np.float32),
            patch_size=patch,
            patch_overlap=max(8, patch // 4),
            inference_device=device,
        )[0].astype(np.uint8)


def collapse_to_three(mask: np.ndarray) -> np.ndarray:
    """Map a 4-class CloudSEN12 mask to clear / cloud / shadow.

    The encoding is the package one: ``0 clear``, ``1 thick``, ``2 thin``,
    ``3 shadow`` (see ``satharmony.models.metrics.CLASS_NAMES``).  Both cloud
    classes become ``1`` and shadow stays ``2``.

    Args:
        mask: 4-class mask, any shape.

    Returns:
        uint8 mask with 0 clear, 1 cloud, 2 shadow.
    """
    return np.where(mask == 3, 2, np.where((mask == 1) | (mask == 2), 1, 0)).astype(np.uint8)


#: Kept name used by the OmniCloudMask path.
ocm_to_three = collapse_to_three


class Predictor:
    """One model behind a ``predict(image) -> classes`` callable."""

    def __init__(self, name: str, kind: str, path: Path | None, device: str):
        self.name = name
        self.kind = kind
        self.path = path
        self.device = device
        self.model = None
        self.checkpoint = None
        self.pad_offsets = PAD_OFFSETS_G4_REAL if name == "g4_real" else None
        if kind == "qa4eo2":
            self.model = load_qa4eo2(path, device)
        elif kind == "unet":
            self.model, self.checkpoint = load_model(path, device=device)

    def predict(self, image: np.ndarray) -> np.ndarray:
        if self.kind == "qa4eo2":
            probabilities = predict_proba_qa4eo2(self.model, image, self.device)
            return probabilities_to_three(probabilities)
        if self.kind == "unet":
            probabilities = predict_proba_unet(
                self.model,
                self.checkpoint,
                image,
                self.device,
                dihedral=True,
                pad_offsets=self.pad_offsets,
            )
            return collapse_to_three(probabilities.argmax(axis=0))
        if self.kind == "ocm":
            return ocm_to_three(ocm_mask(image[list(OCM_BANDS)], self.device))
        raise ValueError(f"unknown kind {self.kind!r}")


# ── metrics ─────────────────────────────────────────────────────────────
def three_class_scores(matrix: np.ndarray) -> dict[str, dict[str, float]]:
    """Per-class scores renamed to the 3-class MSS encoding.

    ``satharmony.models.metrics.per_class_scores`` keys the first three classes
    as ``clear``, ``thick_cloud``, ``thin_cloud`` (CloudSEN12 order).  Here the
    encoding is ``0 clear``, ``1 cloud``, ``2 cloud_shadow``, so the names are
    remapped by position.

    Args:
        matrix: 3 x 3 confusion matrix (rows reference, columns prediction).

    Returns:
        ``{class: {"support", "precision", "recall", "f1", "iou"}}`` with
        ``clear`` / ``cloud`` / ``cloud_shadow``.
    """
    raw = per_class_scores(matrix)
    return {
        "clear": raw["clear"],
        "cloud": raw["thick_cloud"],
        "cloud_shadow": raw["thin_cloud"],
    }


def boundary_map(mask: np.ndarray) -> np.ndarray:
    """One-pixel boundary of a binary mask.

    Args:
        mask: ``(H, W)`` boolean.

    Returns:
        Boolean boundary; empty when the mask is empty or fills everything and
        is all True at the border.
    """
    if not mask.any():
        return np.zeros_like(mask, dtype=bool)
    return mask & ~binary_erosion(mask, border_value=0)


def boundary_f1(
    prediction: np.ndarray, reference: np.ndarray, tolerance: int = BOUNDARY_TOLERANCE
) -> float:
    """Boundary F1 between two binary masks (Csurka et al.).

    Args:
        prediction: ``(H, W)`` boolean prediction of one class.
        reference: ``(H, W)`` boolean reference of the same class.
        tolerance: Distance in pixels under which a boundary pixel counts as
            matched.

    Returns:
        F1 of the boundary precision and recall; 1.0 when both masks are empty
        boundaries and 0.0 when only one of them is.
    """
    predicted_boundary = boundary_map(prediction)
    reference_boundary = boundary_map(reference)
    if not predicted_boundary.any() and not reference_boundary.any():
        return 1.0
    if not predicted_boundary.any() or not reference_boundary.any():
        return 0.0
    distance_to_reference = distance_transform_edt(~reference_boundary)
    distance_to_prediction = distance_transform_edt(~predicted_boundary)
    precision = float((distance_to_reference[predicted_boundary] <= tolerance).mean())
    recall = float((distance_to_prediction[reference_boundary] <= tolerance).mean())
    if precision + recall == 0:
        return 0.0
    return 2 * precision * recall / (precision + recall)


def false_positive_fraction(prediction: np.ndarray, reference: np.ndarray) -> dict[str, float]:
    """Share of the reference-clear pixels that the model paints as cloud/shadow.

    Args:
        prediction: ``(H, W)`` classes.
        reference: ``(H, W)`` classes, same encoding.

    Returns:
        ``{"cloud": fraction, "shadow": fraction, "any": fraction}``.
    """
    clear = reference == 0
    if not clear.any():
        return {"cloud": float("nan"), "shadow": float("nan"), "any": float("nan")}
    return {
        "cloud": float(((prediction == 1) & clear).sum() / clear.sum()),
        "shadow": float(((prediction == 2) & clear).sum() / clear.sum()),
        "any": float(((prediction != 0) & clear).sum() / clear.sum()),
    }


def detection_blocks(
    prediction: np.ndarray, reference: np.ndarray, valid: np.ndarray
) -> list[tuple[int, int, int, int]]:
    """Detections at block level.

    Args:
        prediction: ``(H, W)`` classes.
        reference: ``(H, W)`` classes.
        valid: ``(H, W)`` boolean intersection mask.

    Returns:
        One ``(gt_cloud, pred_cloud, gt_shadow, pred_shadow)`` tuple per block
        with at least half of its pixels valid.
    """
    height, width = reference.shape
    rows = []
    for row in range(0, height, DETECTION_BLOCK):
        for col in range(0, width, DETECTION_BLOCK):
            block_valid = valid[row : row + DETECTION_BLOCK, col : col + DETECTION_BLOCK]
            if block_valid.size == 0 or block_valid.mean() < 0.5:
                continue
            gt = reference[row : row + DETECTION_BLOCK, col : col + DETECTION_BLOCK][block_valid]
            pr = prediction[row : row + DETECTION_BLOCK, col : col + DETECTION_BLOCK][block_valid]
            rows.append(
                (
                    int((gt == 1).mean() >= DETECTION_THRESHOLD),
                    int((pr == 1).mean() >= DETECTION_THRESHOLD),
                    int((gt == 2).mean() >= DETECTION_THRESHOLD),
                    int((pr == 2).mean() >= DETECTION_THRESHOLD),
                )
            )
    return rows


def detection_scores(rows: list[tuple[int, int, int, int]]) -> dict[str, dict[str, float]]:
    """Counts and ratios of the block-level detection, per class.

    Args:
        rows: Output of :func:`detection_blocks`.

    Returns:
        ``{class: {"blocks", "present", "tp", "fp", "fn", "precision",
        "recall", "f1"}}``.
    """
    out = {}
    for position, name in ((0, "cloud"), (2, "cloud_shadow")):
        truth = np.asarray([row[position] for row in rows], dtype=bool)
        guess = np.asarray([row[position + 1] for row in rows], dtype=bool)
        tp = int((truth & guess).sum())
        fp = int((~truth & guess).sum())
        fn = int((truth & ~guess).sum())
        precision = tp / (tp + fp) if tp + fp else float("nan")
        recall = tp / (tp + fn) if tp + fn else float("nan")
        f1 = (
            2 * precision * recall / (precision + recall)
            if np.isfinite(precision) and np.isfinite(recall) and precision + recall
            else float("nan")
        )
        out[name] = {
            "blocks": len(truth),
            "present": int(truth.sum()),
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "precision": float(precision),
            "recall": float(recall),
            "f1": float(f1),
        }
    return out


def pool_detection(scenes: list[dict]) -> dict[str, dict[str, float]]:
    """Pool the block counts of every scene.

    Pooling the counts answers "how many blocks of the test are right", while
    averaging the per-scene ratios would give every scene the same weight.
    Both are written; this one is the headline.

    Args:
        scenes: Per-scene rows of one model.

    Returns:
        Same structure as :func:`detection_scores`, pooled.
    """
    out = {}
    for name in ("cloud", "cloud_shadow"):
        tp = sum(row["detection"][name]["tp"] for row in scenes)
        fp = sum(row["detection"][name]["fp"] for row in scenes)
        fn = sum(row["detection"][name]["fn"] for row in scenes)
        blocks = sum(row["detection"][name]["blocks"] for row in scenes)
        present = sum(row["detection"][name]["present"] for row in scenes)
        precision = tp / (tp + fp) if tp + fp else float("nan")
        recall = tp / (tp + fn) if tp + fn else float("nan")
        f1 = (
            2 * precision * recall / (precision + recall)
            if np.isfinite(precision) and np.isfinite(recall) and precision + recall
            else float("nan")
        )
        out[name] = {
            "blocks": blocks,
            "present": present,
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "precision": float(precision),
            "recall": float(recall),
            "f1": float(f1),
        }
    return out


def score_scene(prediction: np.ndarray, reference: np.ndarray, valid: np.ndarray) -> dict:
    """Every per-scene number of one model."""
    matrix = confusion_matrix(prediction, reference, num_classes=3, ignore_mask=~valid)
    safe_prediction = np.where(valid, prediction, 0).astype(np.uint8)
    safe_reference = np.where(valid, reference, 0).astype(np.uint8)
    cloud = boundary_f1(safe_prediction == 1, safe_reference == 1)
    shadow = boundary_f1(safe_prediction == 2, safe_reference == 2)
    false_positives = false_positive_fraction(safe_prediction, safe_reference)
    rows = detection_blocks(prediction, reference, valid)
    return {
        "confusion": matrix,
        "mean_iou": mean_iou(matrix),
        "overall_accuracy": overall_accuracy(matrix),
        "kappa": cohen_kappa(matrix),
        "boundary_f1_cloud": cloud,
        "boundary_f1_shadow": shadow,
        "boundary_f1_mean": float(np.nanmean([cloud, shadow])),
        "false_positives": false_positives,
        "detection": detection_scores(rows),
        "valid_pixels": int(valid.sum()),
    }


# ── figures ─────────────────────────────────────────────────────────────
def false_colour(image: np.ndarray, bands: tuple[int, int, int] = (3, 1, 0)) -> np.ndarray:
    """Percentile stretch false colour of the MSS stack."""
    rgb = np.stack([image[index] for index in bands], axis=-1)
    out = np.zeros_like(rgb)
    for index in range(3):
        channel = rgb[..., index]
        low, high = np.percentile(channel, [2, 98])
        out[..., index] = np.clip((channel - low) / max(high - low, 1e-6), 0, 1)
    return out


def figure_bars(path: Path, results: dict[str, dict]) -> None:
    """IoU per class and boundary F1 per class, one panel each.

    Args:
        path: Destination PNG.
        results: ``{model: result}`` as returned by the comparison.
    """
    models = list(results)
    positions = np.arange(len(models))
    colours = ["#1b9e77", "#d95f02", "#1f78b4"]  # clear, cloud, cloud shadow
    figure, axes = plt.subplots(1, 2, figsize=(12.0, 4.2), constrained_layout=True)

    width = 0.8 / len(CLASS_NAMES)
    for index, name in enumerate(CLASS_NAMES):
        values = [results[model]["per_class"][name]["iou"] for model in models]
        axes[0].bar(
            positions + index * width - 0.4 + width / 2,
            values,
            width,
            label=name.replace("_", " "),
            color=colours[index],
        )
    axes[0].set_title("IoU per class against the QA4EO-2 labels", fontsize=9, loc="left")
    axes[0].set_ylabel("IoU")
    axes[0].set_ylim(0, 1.0)
    axes[0].grid(axis="y", alpha=0.3)
    axes[0].legend(frameon=False, fontsize=8)

    width = 0.8 / 2
    for index, (key, name) in enumerate(
        (("boundary_mean", "cloud"), ("boundary_mean_shadow", "cloud shadow"))
    ):
        values = [results[model][key] for model in models]
        axes[1].bar(
            positions + index * width - 0.4 + width / 2,
            values,
            width,
            label=name,
            color=colours[index + 1],
        )
    axes[1].set_title(
        "Boundary F1, cloud and cloud shadow only (1 px tolerance at 60 m)",
        fontsize=9,
        loc="left",
    )
    axes[1].set_ylabel("Boundary F1")
    upper = max(
        max(results[model]["boundary_mean"] for model in models),
        max(results[model]["boundary_mean_shadow"] for model in models),
    )
    axes[1].set_ylim(0, float(min(1.0, upper * 1.25)))
    axes[1].grid(axis="y", alpha=0.3)
    axes[1].legend(frameon=False, fontsize=8)

    for axis in axes:
        axis.set_xticks(positions)
        axis.set_xticklabels(models, rotation=15, ha="right", fontsize=8)
    figure.savefig(path, dpi=150)
    plt.close(figure)


