def pick_chips(
    rows: list[dict[str, str]],
    data: Path,
    out: Path,
    size: int = 512,
    count: int = 6,
) -> list[dict]:
    """Choose the chips of the contact sheet from the label statistics.

    The chips are chosen from ``labels_manifest.csv`` so no prediction is
    involved: the two cloudiest scenes, the cloudiest shadow scene, one with
    about 20 % cloud, one nearly clear and the median cloud fraction.  In each
    scene the window with the most valid pixels is used.

    Args:
        rows: Manifest rows of the split.
        data: Root of ``pairs_optimization``.
        out: Folder with ``labels_manifest.csv``.
        size: Chip side in pixels.
        count: Maximum number of chips.

    Returns:
        One dict per chip with ``scene``, ``row``, ``col``, ``label``,
        ``image`` and ``reference``.
    """
    stats = {}
    manifest_csv = out / "labels_manifest.csv"
    if manifest_csv.exists():
        with manifest_csv.open(newline="") as handle:
            stats = {row["id_name"]: row for row in csv.DictReader(handle)}

    def fraction(scene: str, key: str) -> float:
        row = stats.get(scene)
        return float(row[key]) if row and row.get(key) else 0.0

    scenes = [row["id_name"] for row in rows]
    by_cloud = sorted(scenes, key=lambda scene: fraction(scene, "cloud_fraction"))
    chosen: list[tuple[str, str]] = []
    if by_cloud:
        chosen.append((by_cloud[-1], "cloudiest"))
        if len(by_cloud) > 1:
            chosen.append((by_cloud[-2], "second cloudiest"))
        middle = int(np.argmin([abs(fraction(scene, "cloud_fraction") - 0.2) for scene in scenes]))
        chosen.append((scenes[middle], "cloud ~20 %"))
        quiet = [scene for scene in by_cloud if fraction(scene, "cloud_fraction") < 0.01]
        if quiet:
            chosen.append((quiet[0], "clear"))
        chosen.append((by_cloud[len(by_cloud) // 2], "median cloud"))
    by_shadow = sorted(scenes, key=lambda scene: fraction(scene, "shadow_fraction"))
    if by_shadow:
        chosen.append((by_shadow[-1], "most shadow"))

    chips = []
    seen = set()
    for scene, label in chosen:
        if scene in seen or len(chips) >= count:
            continue
        seen.add(scene)
        folder = data / "pairs_optimization" / scene
        image, _ = read_mss60(folder / "mss_original.tif")
        with rasterio.open(reference_path(folder)) as src:
            reference = src.read(1)
        valid = valid_mask(image) & (reference != IGNORE)
        height, width = valid.shape
        best = None
        for row in range(0, max(height - size, 1), size):
            for col in range(0, max(width - size, 1), size):
                fraction_valid = float(valid[row : row + size, col : col + size].mean())
                if best is None or fraction_valid > best[2]:
                    best = (row, col, fraction_valid)
        if best is None or best[2] < 0.5:
            continue
        row, col = best[0], best[1]
        chips.append(
            {
                "scene": scene,
                "label": f"{scene} ({label})",
                "row": row,
                "col": col,
                "image": image[:, row : row + size, col : col + size],
                "reference": reference[row : row + size, col : col + size],
            }
        )
    return chips


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--labels", type=Path, default=DEFAULT_LABELS)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument(
        "--models",
        nargs="+",
        default=["ocm_mss", "qa4eo2_jan4", "g4", "g4b", "g4_cal", "g4b_cal", "g4_real"],
    )
    parser.add_argument("--device", default="cuda:0" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args(argv)

    rows = read_test_rows(args.manifest)
    if args.limit:
        rows = rows[: args.limit]
    args.out.mkdir(parents=True, exist_ok=True)

    registry = {
        "ocm_mss": ("ocm", None),
        "qa4eo2_jan4": ("qa4eo2", DEFAULT_QA4EO2_JAN),
        "g4": ("unet", DEFAULT_G4),
        "g4b": ("unet", DEFAULT_G4B),
        "g4_cal": ("unet", DEFAULT_G4_CAL),
        "g4b_cal": ("unet", DEFAULT_G4B_CAL),
        "g4_real": ("unet", DEFAULT_G4_REAL),
    }
    unknown = [name for name in args.models if name not in registry]
    if unknown:
        raise SystemExit(f"unknown models: {unknown}")

    results: dict[str, dict] = {}
    per_scene: dict[str, list[dict]] = {}
    started = time.time()

    for name in args.models:
        kind, path = registry[name]
        print(f"== {name} ({kind})")
        predictor = Predictor(name, kind, path, args.device)
        matrices = np.zeros((3, 3), dtype=np.int64)
        scene_rows: list[dict] = []
        for number, row in enumerate(rows, 1):
            scene = row["id_name"]
            folder = args.data / "pairs_optimization" / scene
            image, _ = read_mss60(folder / "mss_original.tif")
            with rasterio.open(reference_path(folder)) as src:
                reference = src.read(1)
            valid = valid_mask(image) & (reference != IGNORE)
            prediction = predictor.predict(image)
            scored = score_scene(prediction, reference, valid)
            matrices += scored["confusion"]
            scores = three_class_scores(scored["confusion"])
            total = int(scored["confusion"].sum())
            scene_rows.append(
                {
                    "id_name": scene,
                    "valid_pixels": scored["valid_pixels"],
                    "mean_iou": scored["mean_iou"],
                    "overall_accuracy": scored["overall_accuracy"],
                    "kappa": scored["kappa"],
                    "class_ratio": {
                        key: float(scored["confusion"][index].sum() / total)
                        for index, key in enumerate(CLASS_NAMES)
                    },
                    "per_class": {key: values["iou"] for key, values in scores.items()},
                    "boundary_f1_cloud": scored["boundary_f1_cloud"],
                    "boundary_f1_shadow": scored["boundary_f1_shadow"],
                    "false_positives": scored["false_positives"],
                    "detection": scored["detection"],
                }
            )
            print(
                f"  [{number}/{len(rows)}] {scene} mIoU {scored['mean_iou']:.3f} "
                f"OA {scored['overall_accuracy']:.3f} B-F1 {scored['boundary_f1_cloud']:.3f}"
            )
            del prediction

        scores = three_class_scores(matrices)
        results[name] = {
            "confusion_matrix": matrices.tolist(),
            "per_class": scores,
            "mean_iou": mean_iou(matrices),
            "overall_accuracy": overall_accuracy(matrices),
            "cohen_kappa": cohen_kappa(matrices),
            "n_pixels": int(matrices.sum()),
            "boundary_mean": float(np.nanmean([r["boundary_f1_cloud"] for r in scene_rows])),
            "boundary_mean_shadow": float(np.nanmean([r["boundary_f1_shadow"] for r in scene_rows])),
            "false_positives": {
                # pooled over every reference-clear pixel of the split
                "cloud": float(matrices[0, 1] / matrices[0].sum()) if matrices[0].sum() else float("nan"),
                "shadow": float(matrices[0, 2] / matrices[0].sum()) if matrices[0].sum() else float("nan"),
                "any": float((matrices[0, 1] + matrices[0, 2]) / matrices[0].sum())
                if matrices[0].sum()
                else float("nan"),
            },
            "false_positives_scene_mean": {
                key: float(np.nanmean([r["false_positives"][key] for r in scene_rows]))
                for key in ("cloud", "shadow", "any")
            },
            "detection": pool_detection(scene_rows),
        }
        per_scene[name] = scene_rows
        print(
            f"  pooled mIoU {results[name]['mean_iou']:.3f} "
            f"OA {results[name]['overall_accuracy']:.3f} "
            f"kappa {results[name]['cohen_kappa']:.3f}"
        )

    payload = {
        "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "elapsed_s": round(time.time() - started, 1),
        "reference": "label_qa4eo_2_60m.tif (QA4EO-2 on mss_original, 60 m)",
        "mask": "all four MSS bands > 0 and label != 255 (intersection)",
        "boundary_tolerance_px": BOUNDARY_TOLERANCE,
        "detection": {
            "block": DETECTION_BLOCK,
            "threshold": DETECTION_THRESHOLD,
            "min_valid": 0.5,
        },
        "scenes": len(rows),
        "models": {
            name: {"kind": registry[name][0], "path": str(registry[name][1] or "omnicloudmask")}
            for name in args.models
        },
        "results": results,
        "per_scene": per_scene,
    }
    (args.out / "comparison.json").write_text(json.dumps(payload, indent=1, default=float))
    write_tables(args.out, results, per_scene)

    if not args.no_figures:
        figures = args.out / "figures"
        figures.mkdir(parents=True, exist_ok=True)
        figure_bars(figures / "bars.png", results)

    print(f"written: {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
